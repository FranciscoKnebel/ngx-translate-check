import type { Command } from "commander";

import { diffKeys } from "../utils/dictionary.js";
import { readFilesOutput, writeJsonOrStdout } from "../utils/files.js";

interface DiffCommandOptions {
  base: string;
  json?: string;
}

type LanguageDiff = Record<string, Record<string, number>>;

export function registerDiffCommand(program: Command): void {
  program
    .command("diff <path>")
    .option(
      "--base <index>",
      "Diff to language with base <index>. A negative index compares all languages.",
      "0",
    )
    .option("--json <path>", "Save output to <path> file.")
    .description(
      "Receives a JSON file generated by the files command and shows differences between translation files.",
    )
    .action(async (fileName: string, options: DiffCommandOptions) => {
      const report = await readFilesOutput(fileName);
      const translations = report.translations;
      const languages = Object.keys(translations);
      if (!/^[+-]?\d+$/.test(options.base) || !Number.isSafeInteger(Number(options.base))) {
        throw new Error("Base language index must be an integer.");
      }
      const baseIndex = Number(options.base);

      const response =
        baseIndex < 0
          ? allLanguagesDiff(languages, translations)
          : baseLanguageDiff(languages, translations, baseIndex);

      await writeJsonOrStdout(options.json, response);
    });
}

function diffForBase(
  languages: string[],
  translations: Record<string, Record<string, number>>,
  baseIndex: number,
): LanguageDiff[] {
  const baseLanguage = languages[baseIndex];
  if (!baseLanguage) {
    throw new Error("Base language index is outside the available translation files.");
  }

  const baseTranslations = translations[baseLanguage];
  if (!baseTranslations) {
    throw new Error("Translation data is missing for " + baseLanguage + ".");
  }

  const responses: LanguageDiff[] = [];
  languages.forEach((language, index) => {
    if (index === baseIndex) {
      return;
    }

    const languageTranslations = translations[language];
    if (!languageTranslations) {
      throw new Error("Translation data is missing for " + language + ".");
    }

    console.log("Getting difference between " + baseLanguage + " and " + language + ".");
    const [baseOnly, languageOnly] = diffKeys(baseTranslations, languageTranslations);
    responses.push({
      ["base " + baseLanguage]: baseOnly,
      ["compare with " + language]: languageOnly,
    });
  });

  return responses;
}

function baseLanguageDiff(
  languages: string[],
  translations: Record<string, Record<string, number>>,
  baseIndex: number,
): LanguageDiff {
  return diffForBase(languages, translations, baseIndex)[0] ?? {};
}

function allLanguagesDiff(
  languages: string[],
  translations: Record<string, Record<string, number>>,
): LanguageDiff[][] {
  const responses: LanguageDiff[][] = [];
  for (let baseIndex = 0; baseIndex < languages.length; baseIndex += 1) {
    responses.push(diffForBase(languages, translations, baseIndex));
  }

  return responses;
}
